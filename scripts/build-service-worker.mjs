import { readdir, readFile, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
const files = []
async function collect(directory = 'dist', prefix = './') {
  for (const entry of await readdir(directory, { withFileTypes:true })) {
    if (entry.isDirectory()) await collect(directory + '/' + entry.name, prefix + entry.name + '/')
    else if (entry.name !== 'sw.js') files.push(prefix + entry.name)
  }
}
await collect()
const hash = createHash('sha256')
for (const file of files.sort()) hash.update(await readFile('dist/' + file.slice(2)))
const version = hash.digest('hex').slice(0, 12)
await writeFile('dist/sw.js', `// Generated from this build's assets. Do not edit this file.
const PREFIX = 'roam-static:' + self.registration.scope + ':';
const CACHE = PREFIX + '${version}';
const ASSETS = ${JSON.stringify(files)};
self.addEventListener('install', event => event.waitUntil(
  caches.open(CACHE).then(cache => cache.addAll(ASSETS)).then(() => self.skipWaiting())
));
self.addEventListener('activate', event => event.waitUntil((async () => {
  for (const key of await caches.keys()) {
    if ((key.startsWith(PREFIX) && key !== CACHE) || key === 'roam-offline-v1' || key.startsWith('roam-vue:' + self.registration.scope + ':')) await caches.delete(key);
  }
  await self.clients.claim();
})()));
self.addEventListener('fetch', event => {
  if (event.request.method !== 'GET') return;
  const url = new URL(event.request.url);
  if (!url.href.startsWith(self.registration.scope)) return;
  // Fresh HTML when online; the cached app shell when travelling offline.
  if (event.request.mode === 'navigate') {
    event.respondWith(fetch(event.request).catch(() => caches.match(new URL('./index.html', self.registration.scope))));
  } else if (ASSETS.some(asset => new URL(asset, self.registration.scope).href === url.href)) {
    event.respondWith(caches.match(event.request).then(cached => cached || fetch(event.request)));
  }
});
`)
console.log('Offline app cache generated for ' + files.length + ' files.')
