import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
const sample=JSON.parse(await readFile(new URL('../fixtures/example-trip.json',import.meta.url),'utf8'))
const activity=(id,title,time,category='sightseeing')=>({id,title,time,category,location:'',notes:'',url:'',done:false})
test('imported, newly added and edited activities display chronologically everywhere',async({page})=>{
  const plan=structuredClone(sample)
  plan.days['2026-11-12'].activities=[activity('dinner','Evening dinner','18:00','food'),activity('walk','Morning walk','08:00'),activity('idea','Untimed idea',''),activity('train','Midday train','12:00','transport')]
  await page.goto('/')
  await page.locator('input[type=file]').setInputFiles({name:'trip.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(plan))})
  const cell=page.getByRole('button',{name:'Thursday, 12 November 2026',exact:true})
  await expect(cell.locator('.cal-activity')).toHaveText(['08:00 Morning walk','12:00 Midday train'])
  await expect(cell.locator('.city-pill')).toContainText('Harbor City')
  await cell.click()
  await expect(page.locator('.day-drawer .drawer-act strong')).toHaveText(['Morning walk','Midday train','Evening dinner','Untimed idea'])
  expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('roam-personal-trip-v1')).days['2026-11-12'].activities.map(a=>a.id))).toEqual(['dinner','walk','idea','train'])
  await page.getByRole('button',{name:'Edit Evening dinner',exact:true}).click()
  await page.getByLabel('Time (optional)',{exact:true}).fill('07:00')
  await page.getByRole('button',{name:'Save changes',exact:true}).click()
  await expect(page.locator('.day-drawer .drawer-act strong')).toHaveText(['Evening dinner','Morning walk','Midday train','Untimed idea'])
  await page.getByRole('button',{name:'Add activity',exact:true}).click()
  await page.getByLabel('Activity name *',{exact:true}).fill('New breakfast')
  await page.getByLabel('Time (optional)',{exact:true}).fill('07:30')
  await page.getByRole('button',{name:'Save changes',exact:true}).click()
  await expect(page.locator('.day-drawer .drawer-act strong')).toHaveText(['Evening dinner','New breakfast','Morning walk','Midday train','Untimed idea'])
  await page.getByRole('button',{name:'Close day details',exact:true}).click()
  await page.getByRole('button',{name:'Daily itinerary',exact:true}).click()
  await expect(page.locator('[data-date-drop="2026-11-12"] .a-title')).toHaveText(['Evening dinner','New breakfast','Morning walk','Midday train','Untimed idea'])
  await page.reload()
  await page.getByRole('button',{name:'Daily itinerary',exact:true}).click()
  await expect(page.locator('[data-date-drop="2026-11-12"] .a-title')).toHaveText(['Evening dinner','New breakfast','Morning walk','Midday train','Untimed idea'])
})
