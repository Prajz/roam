import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
const fixture=await readFile(new URL('../fixtures/example-trip.json',import.meta.url))
const sample=JSON.parse(fixture)
const welcome=page=>page.getByRole('heading',{name:'Let’s get your trip started.',exact:true})
async function basics(page) {
  await page.getByRole('button',{name:/Plan a new trip/}).click()
  await page.getByLabel('Trip name',{exact:true}).fill('Our spring adventure')
  await page.getByLabel('Start date',{exact:true}).fill('2027-03-01')
  await page.getByLabel('End date',{exact:true}).fill('2027-03-08')
  await page.getByRole('button',{name:'Continue',exact:true}).click()
}
async function places(page) {
  await page.getByLabel('Places to visit, in order').fill('Harbor City\nOld Town')
  await page.getByLabel('Your travel pace').selectOption('relaxed')
  await page.getByLabel('Culture',{exact:true}).check()
  await page.getByLabel('Anything else? (optional)').fill('Keep some afternoons free')
  await page.getByRole('button',{name:'Continue',exact:true}).click()
}
async function fits(page) { expect(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth)).toBe(true) }
test('first visit builds an editable trip from questions and overnight flights',async({page},info)=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message))
  await page.goto('/')
  await expect(welcome(page)).toBeVisible()
  await fits(page)
  await page.screenshot({path:`test-results/${info.project.name}-onboarding-welcome.png`})
  await basics(page)
  await places(page)
  await page.locator('summary').filter({hasText:'Outbound flight'}).click()
  const outbound=page.locator('details').filter({has:page.locator('summary').filter({hasText:'Outbound flight'})})
  await outbound.getByLabel('Add this flight to the plan').check()
  await outbound.getByLabel('From airport',{exact:true}).fill('Home airport')
  await outbound.getByLabel('To airport',{exact:true}).fill('Coastal airport')
  await outbound.getByLabel('Flight number (optional)').fill('AB123')
  await outbound.getByLabel('Departure date',{exact:true}).fill('2027-03-01')
  await outbound.getByLabel('Departure time (optional)').fill('22:30')
  await outbound.getByLabel('Arrival date',{exact:true}).fill('2027-03-02')
  await outbound.getByLabel('Arrival time (optional)').fill('07:00')
  await fits(page)
  await page.screenshot({path:`test-results/${info.project.name}-onboarding-flights.png`,fullPage:true})
  await page.getByRole('button',{name:'Create my trip',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Our spring adventure',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Daily itinerary',exact:true}).click()
  await expect(page.getByRole('button',{name:'Fly Home airport → Coastal airport (AB123) 22:30',exact:true})).toBeVisible()
  await fits(page)
  await page.getByRole('button',{name:'Trip notes',exact:true}).click()
  await expect(page.getByLabel('Trip overview',{exact:true})).toContainText('Keep some afternoons free')
  const downloadPromise=page.waitForEvent('download')
  await page.getByRole('button',{name:'Download JSON backup',exact:true}).click()
  const exported=JSON.parse(await readFile(await (await downloadPromise).path(),'utf8'))
  expect(exported.schemaVersion).toBe(1)
  expect(exported.stays[0].from).toBe('2027-03-02')
  expect(exported.stays.map(s=>s.name)).toEqual(['Harbor City','Old Town'])
  expect(exported.days['2027-03-01'].activities[0].time).toBe('22:30')
  expect(exported.days['2027-03-02'].activities.some(a=>a.title==='Arrive at Coastal airport (AB123)')).toBe(true)
  await page.reload()
  await expect(welcome(page)).toHaveCount(0)
  await expect(page.getByRole('heading',{name:'Our spring adventure',exact:true})).toBeVisible()
  expect(errors).toEqual([])
})
test('JSON-first onboarding, errors and returning trips preserve the existing plan',async({page})=>{
  await page.goto('/')
  await expect(page.getByRole('button',{name:/I have a JSON plan/})).toBeVisible()
  await page.locator('input[type=file]').setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from('{bad')})
  await expect(page.getByRole('status')).toContainText('Could not import trip')
  await expect(welcome(page)).toBeVisible()
  await page.locator('input[type=file]').setInputFiles({name:'trip.json',mimeType:'application/json',buffer:fixture})
  await expect(page.getByRole('heading',{name:sample.name,exact:true})).toBeVisible()
  await page.reload()
  await expect(welcome(page)).toHaveCount(0)
  await page.getByRole('button',{name:'Trip notes',exact:true}).click()
  page.once('dialog',dialog=>dialog.accept())
  await page.getByRole('button',{name:'Start a fresh trip',exact:true}).click()
  await expect(welcome(page)).toBeVisible()
  await page.getByRole('button',{name:'Keep my current trip',exact:true}).click()
  await expect(page.getByRole('heading',{name:sample.name,exact:true})).toBeVisible()
  expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('roam-personal-trip-v1')).name)).toBe(sample.name)
})
test('back preserves answers, impossible routes are explained, and skipping is remembered',async({page})=>{
  await page.goto('/')
  await basics(page)
  await page.getByLabel('Places to visit, in order').fill('Harbor City\nOld Town')
  await page.getByRole('button',{name:'Back',exact:true}).click()
  await expect(page.getByLabel('Trip name',{exact:true})).toHaveValue('Our spring adventure')
  await page.getByLabel('End date',{exact:true}).fill('2027-03-01')
  await page.getByRole('button',{name:'Continue',exact:true}).click()
  await expect(page.getByLabel('Places to visit, in order')).toHaveValue('Harbor City\nOld Town')
  await page.getByRole('button',{name:'Continue',exact:true}).click()
  await expect(page.getByRole('alert')).toContainText('more places than nights')
  await page.getByRole('button',{name:'Skip for now',exact:true}).click()
  await expect(page.getByRole('heading',{name:'My next adventure',exact:true})).toBeVisible()
  await page.reload()
  await expect(welcome(page)).toHaveCount(0)
})
test('a returning pre-onboarding trip opens directly',async({page})=>{
  await page.addInitScript(plan=>localStorage.setItem('roam-personal-trip-v1',JSON.stringify(plan)),sample)
  await page.goto('/')
  await expect(welcome(page)).toHaveCount(0)
  await expect(page.getByRole('heading',{name:sample.name,exact:true})).toBeVisible()
})
test('flights can be skipped and the generated stays remain editable',async({page})=>{
  await page.goto('/')
  await basics(page)
  await places(page)
  await page.getByRole('button',{name:'Create my trip',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Our spring adventure',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Destinations & stays',exact:true}).click()
  await page.getByRole('button',{name:'Edit Harbor City',exact:true}).click()
  await page.getByLabel('Hotel / accommodation',{exact:true}).fill('Our first hotel')
  await page.getByRole('button',{name:'Save changes',exact:true}).click()
  await expect(page.getByText('Our first hotel',{exact:true})).toBeVisible()
})
