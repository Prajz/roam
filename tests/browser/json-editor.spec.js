import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
const sample=JSON.parse(await readFile(new URL('../fixtures/example-trip.json',import.meta.url),'utf8'))
async function settings(page) {
  await page.getByRole('button',{name:'Trip settings',exact:true}).locator('visible=true').click()
  await page.getByRole('button',{name:'JSON editor',exact:true}).click()
  return page.getByLabel('Trip JSON',{exact:true})
}
test.beforeEach(async({page})=>{
  page.on('dialog',dialog=>dialog.accept())
  await page.goto('/')
  await page.locator('input[type=file]').setInputFiles({name:'trip.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(sample))})
  await expect(page.getByRole('heading',{name:sample.name,exact:true})).toBeVisible()
})
test('edit JSON inline, format, apply and persist the complete plan',async({page},info)=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message))
  const source=await settings(page)
  expect(JSON.parse(await source.inputValue())).toEqual(sample)
  const draft=structuredClone(sample)
  draft.name='Our edited trip'
  draft.days['2026-11-12'].notes='Bring a camera'
  draft.days['2026-11-12'].activities.push({id:'json-activity',title:'Walk by the river',time:'18:00',location:'Waterfront',category:'sightseeing',notes:'Flexible evening plan',url:'',done:false,price:'',currency:'',booked:false,paid:false})
  await source.fill(JSON.stringify(draft))
  await expect(page.locator('#json-validation')).toContainText('Valid JSON')
  expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('roam-personal-trip-v1')).name)).toBe(sample.name)
  await page.getByRole('button',{name:'Format JSON',exact:true}).click()
  await expect(source).toHaveValue(JSON.stringify(draft,null,2))
  expect(await source.evaluate(node=>node.scrollLeft)).toBe(0)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  expect(await page.locator('dialog.modal').evaluate(node=>node.scrollWidth<=node.clientWidth)).toBe(true)
  await page.screenshot({path:`test-results/${info.project.name}-json-editor.png`})
  await page.getByRole('button',{name:'Apply JSON',exact:true}).click()
  await expect(page.locator('dialog.modal')).not.toBeVisible()
  await expect(page.getByRole('heading',{name:draft.name,exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Thursday, 12 November 2026',exact:true}).click()
  await expect(page.getByText('Walk by the river',{exact:true})).toBeVisible()
  await expect(page.getByLabel('Extra notes',{exact:true})).toHaveValue('Bring a camera')
  await page.reload()
  await expect(page.getByRole('heading',{name:draft.name,exact:true})).toBeVisible()
  expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('roam-personal-trip-v1')))).toEqual(draft)
  expect(errors).toEqual([])
})
test('invalid drafts get live feedback, reset and cancel preserve the saved trip',async({page})=>{
  const source=await settings(page)
  await source.fill('{broken')
  await expect(page.locator('#json-validation')).toContainText('JSON syntax')
  await expect(page.getByRole('button',{name:'Apply JSON',exact:true})).toBeDisabled()
  await expect(page.getByRole('button',{name:'Format JSON',exact:true})).toBeDisabled()
  const invalid=structuredClone(sample);invalid.startDate='2026-11-13'
  await source.fill(JSON.stringify(invalid))
  await expect(source).toHaveAttribute('aria-invalid','true')
  await expect(page.getByRole('button',{name:'Apply JSON',exact:true})).toBeDisabled()
  await expect(page.getByRole('button',{name:'Format JSON',exact:true})).toBeEnabled()
  expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('roam-personal-trip-v1')))).toEqual(sample)
  await page.getByRole('button',{name:'Reset draft',exact:true}).click()
  expect(JSON.parse(await source.inputValue())).toEqual(sample)
  await expect(source).toHaveAttribute('aria-invalid','false')
  await source.fill(JSON.stringify({...sample,name:'Unsaved draft'}))
  await page.getByRole('button',{name:'Cancel',exact:true}).locator('visible=true').click()
  await page.reload()
  await expect(page.getByRole('heading',{name:sample.name,exact:true})).toBeVisible()
  const again=await settings(page)
  expect(JSON.parse(await again.inputValue())).toEqual(sample)
})
test('normal trip settings still work and edited HTML remains text',async({page})=>{
  const source=await settings(page)
  const draft={...sample,name:'<img src=x onerror=alert(1)>',overview:'</textarea><script>alert(1)</script>'}
  await source.fill(JSON.stringify(draft))
  await page.getByRole('button',{name:'Apply JSON',exact:true}).click()
  await expect(page.getByRole('heading',{name:draft.name,exact:true})).toBeVisible()
  await expect(page.locator('.hero img')).toHaveCount(0)
  const again=await settings(page)
  expect(JSON.parse(await again.inputValue())).toEqual(draft)
  await page.getByRole('button',{name:'Trip details',exact:true}).click()
  await page.getByLabel('Trip name',{exact:true}).fill('A normal settings edit')
  await page.getByRole('button',{name:'Save changes',exact:true}).click()
  await expect(page.getByRole('heading',{name:'A normal settings edit',exact:true})).toBeVisible()
  expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('roam-personal-trip-v1')).overview)).toBe(draft.overview)
})
