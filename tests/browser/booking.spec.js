import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
const sample=JSON.parse(await readFile(new URL('../fixtures/example-trip.json',import.meta.url),'utf8'))
test('hotel and activity cost/status controls save separately from completion and survive export/reload',async({page},info)=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message))
  await page.goto('/')
  await page.locator('input[type=file]').setInputFiles({name:'trip.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(sample))})
  await page.getByRole('button',{name:'Destinations & stays',exact:true}).click()
  await page.getByRole('button',{name:'Edit Harbor City',exact:true}).click()
  await page.getByLabel('Hotel / accommodation',{exact:true}).fill('Harbour Hotel')
  await page.getByLabel('Total hotel price (optional)',{exact:true}).fill('520.50')
  await page.getByRole('button',{name:'Save changes',exact:true}).click()
  await expect(page.getByRole('alert')).toContainText('currency is required')
  await page.getByLabel('Currency',{exact:true}).fill('cny')
  await page.getByLabel('Hotel booked',{exact:true}).check()
  await page.getByRole('button',{name:'Save changes',exact:true}).click()
  const hotel=page.locator('.stay-card').filter({has:page.getByText('Harbour Hotel',{exact:true})})
  await expect(hotel.locator('.booking-meta')).toContainText('CNY')
  await expect(hotel.locator('.booking-meta')).toContainText('520.50')
  await expect(hotel.locator('.booking-meta')).toContainText('Booked')
  await expect(hotel.locator('.booking-meta')).toContainText('Payment not marked')
  await page.getByRole('button',{name:'Edit Harbor City',exact:true}).click()
  await expect(page.getByLabel('Hotel booked',{exact:true})).toBeChecked()
  await expect(page.getByLabel('Hotel paid',{exact:true})).not.toBeChecked()
  await page.getByLabel('Hotel paid',{exact:true}).check()
  await page.getByRole('button',{name:'Save changes',exact:true}).click()
  await page.getByRole('button',{name:'Calendar',exact:true}).first().click()
  await page.getByRole('button',{name:'Thursday, 12 November 2026',exact:true}).click()
  await page.getByRole('button',{name:'Edit Arrive at the coast',exact:true}).click()
  await page.getByLabel('Activity price (optional)',{exact:true}).fill('80')
  await page.getByLabel('Currency',{exact:true}).fill('CNY')
  await page.getByLabel('Booked',{exact:true}).check()
  await page.getByLabel('Paid',{exact:true}).check()
  await page.getByRole('button',{name:'Save changes',exact:true}).click()
  const activity=page.locator('.drawer-act').filter({has:page.getByText('Arrive at the coast',{exact:true})})
  await expect(activity.locator('.booking-meta')).toContainText('CNY')
  await expect(activity.locator('.booking-meta')).toContainText('80.00')
  await expect(activity.locator('.booking-state')).toHaveText(['Booked','Paid'])
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:`test-results/${info.project.name}-booking-status.png`})
  await page.getByRole('button',{name:'Edit Arrive at the coast',exact:true}).click()
  await expect(page.getByLabel('Mark as completed',{exact:true})).not.toBeChecked()
  await page.getByRole('button',{name:'Cancel',exact:true}).click()
  await page.getByRole('button',{name:'Close day details',exact:true}).click()
  await page.getByRole('button',{name:'Daily itinerary',exact:true}).click()
  await expect(page.locator('[data-activity-id="activity-2"] .booking-meta')).toContainText('80.00')
  await page.getByRole('button',{name:'Trip notes',exact:true}).click()
  const download=page.waitForEvent('download')
  await page.getByRole('button',{name:'Download JSON backup',exact:true}).click()
  const exported=JSON.parse(await readFile(await (await download).path(),'utf8'))
  expect(exported.stays[0]).toMatchObject({price:520.5,currency:'CNY',booked:true,paid:true})
  expect(exported.days['2026-11-12'].activities[0]).toMatchObject({price:80,currency:'CNY',booked:true,paid:true,done:false})
  await page.reload()
  const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('roam-personal-trip-v1')))
  expect(saved).toEqual(exported)
  await page.getByRole('button',{name:'Trip settings',exact:true}).locator('visible=true').click()
  await page.getByRole('button',{name:'JSON editor',exact:true}).click()
  const invalid=structuredClone(exported);invalid.stays[0].price=-1
  await page.getByLabel('Trip JSON',{exact:true}).fill(JSON.stringify(invalid))
  await expect(page.getByRole('button',{name:'Apply JSON',exact:true})).toBeDisabled()
  await expect(page.locator('#json-validation')).toContainText('price')
  expect(errors).toEqual([])
})
