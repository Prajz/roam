import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
const fixture=JSON.parse(await readFile(new URL('../fixtures/example-trip.json',import.meta.url),'utf8'))
test('destination arrival/departure times persist and appear in cards, calendar, daily view and JSON',async({page},info)=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message))
  const old=structuredClone(fixture)
  for(const stay of old.stays){delete stay.checkInTime;delete stay.checkOutTime}
  await page.goto('/')
  await page.locator('input[type=file]').setInputFiles({name:'legacy-trip.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(old))})
  await page.getByRole('button',{name:'Destinations & stays',exact:true}).click()
  await page.getByRole('button',{name:'Edit Harbor City',exact:true}).click()
  await expect(page.getByLabel('Arrival / check-in time (optional)',{exact:true})).toHaveValue('')
  await page.getByLabel('Arrival / check-in time (optional)',{exact:true}).fill('08:30')
  await page.getByLabel('Departure / check-out time (optional)',{exact:true}).fill('18:00')
  await page.getByRole('button',{name:'Save changes',exact:true}).click()
  const card=page.locator('.stay-card').filter({has:page.getByText('Harbor City',{exact:true})})
  await expect(card.locator('.stay-meta')).toContainText('at 08:30')
  await expect(card.locator('.stay-meta')).toContainText('at 18:00')
  await page.getByRole('button',{name:'Calendar',exact:true}).first().click()
  const checkout=page.getByRole('button',{name:'Sunday, 15 November 2026',exact:true})
  await expect(checkout.locator('.city-time')).toContainText('Out 18:00')
  await checkout.click()
  await expect(page.getByRole('button',{name:'Edit timing for Leave Harbor City',exact:true})).toContainText('18:00')
  await page.getByRole('button',{name:'Edit timing for Arrive in Old Town',exact:true}).click()
  await page.getByLabel('Arrival / check-in time (optional)',{exact:true}).fill('21:00')
  await page.getByRole('button',{name:'Save changes',exact:true}).click()
  await expect(page.getByRole('button',{name:'Edit timing for Arrive in Old Town',exact:true})).toContainText('21:00')
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:`test-results/${info.project.name}-stay-times.png`})
  await page.getByRole('button',{name:'Close day details',exact:true}).click()
  await page.getByRole('button',{name:'Daily itinerary',exact:true}).click()
  await expect(page.locator('[data-date-drop="2026-11-15"] .stay-transitions')).toContainText('18:00')
  await expect(page.locator('[data-date-drop="2026-11-15"] .stay-transitions')).toContainText('21:00')
  await page.getByRole('button',{name:'Trip settings',exact:true}).locator('visible=true').click()
  await page.getByRole('button',{name:'JSON editor',exact:true}).click()
  const source=page.getByLabel('Trip JSON',{exact:true})
  const plan=JSON.parse(await source.inputValue())
  expect(plan.stays[0].checkInTime).toBe('08:30');expect(plan.stays[0].checkOutTime).toBe('18:00')
  expect(plan.stays[1].checkInTime).toBe('21:00')
  await source.fill(JSON.stringify({...plan,stays:plan.stays.map((stay,i)=>i===0?{...stay,checkOutTime:'25:00'}:stay)}))
  await expect(page.getByRole('button',{name:'Apply JSON',exact:true})).toBeDisabled()
  await expect(page.locator('#json-validation')).toContainText('checkOutTime')
  await page.getByRole('button',{name:'Cancel',exact:true}).locator('visible=true').click()
  await page.reload()
  const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('roam-personal-trip-v1')))
  expect(saved.stays[0].checkOutTime).toBe('18:00');expect(saved.stays[1].checkInTime).toBe('21:00')
  expect(errors).toEqual([])
})
